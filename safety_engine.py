def evaluate_contrast_rules(
    contrast_rules: List[Dict[str, Any]],
    patient_data: Dict[str, Any]
) -> List[SafetyFlag]:
    """
    Evaluate a list of contrast_rule rows against extracted patient data.
    Returns a list of SafetyFlag objects (triggered and untriggered).
    """
    flags = []
    
    for rule in contrast_rules:
        rule_type = rule["rule_type"]
        condition = rule.get("condition_json", {})
        if isinstance(condition, str):
            condition = json.loads(condition)
        
        triggered = False
        details = {}
        
        if rule_type == "egfr_check":
            triggered, details = _check_egfr(condition, patient_data)
        elif rule_type == "allergy_check":
            triggered, details = _check_allergies(condition, patient_data)
        elif rule_type == "pregnancy_check":
            triggered, details = _check_pregnancy(condition, patient_data)
        elif rule_type == "bmi_check":
            triggered, details = _check_bmi(condition, patient_data)
        
        flag = SafetyFlag(
            rule_type=rule_type,
            severity=rule.get("severity", "warning"),
            message=rule["alert_message"] if triggered else f"✅ {rule_type} — Passed",
            triggered=triggered,
            action=rule["action_if_triggered"],
            details=details,
        )
        
        # Attach premedication or substitute info if triggered
        if triggered:
            if rule.get("premedication_text"):
                flag.details["premedication_text"] = rule["premedication_text"]
            if rule.get("substitute_protocol_id"):
                flag.details["substitute_protocol_id"] = rule["substitute_protocol_id"]
        
        flags.append(flag)
    
    return flags


def _check_egfr(condition: dict, patient_data: dict) -> tuple:
    """Check if patient's eGFR meets the minimum threshold."""
    egfr_data = patient_data.get("egfr")
    min_egfr = condition.get("egfr_min", 30)
    max_age_days = condition.get("max_age_days", 90)
    
    if not egfr_data or egfr_data.get("value") is None:
        return False, {"status": "no_data", "note": "No eGFR on file — manual check required"}
    
    value = egfr_data["value"]
    details = {"patient_egfr": value, "threshold": min_egfr}
    
    # Check staleness
    if egfr_data.get("date"):
        try:
            result_date = datetime.strptime(str(egfr_data["date"])[:10], "%Y-%m-%d")
            age_days = (datetime.now() - result_date).days
            details["result_age_days"] = age_days
            if age_days > max_age_days:
                details["stale"] = True
                details["note"] = f"eGFR result is {age_days} days old (max allowed: {max_age_days})"
        except (ValueError, TypeError):
            pass
    
    triggered = isinstance(value, (int, float)) and value < min_egfr
    return triggered, details


def _check_allergies(condition: dict, patient_data: dict) -> tuple:
    """Check if patient has allergies to specified contrast agents."""
    from medical_ontology import CONTRAST_ALLERGY_MAP
    
    agents = condition.get("agents", [])
    patient_allergies = [a.lower() for a in patient_data.get("allergies", [])]
    patient_allergy_codes = patient_data.get("allergy_codes", [])
    
    matches = []
    
    # Pre-calculate target codes and classes for the rule's agents
    target_rxnorms = set()
    target_snomeds = set()
    for agent in agents:
        agent_lower = agent.lower().strip()
        # Look up in mapping
        # 1. Direct match by key
        if agent_lower in CONTRAST_ALLERGY_MAP:
            target_rxnorms.add(CONTRAST_ALLERGY_MAP[agent_lower]["rxnorm"])
            target_snomeds.add(CONTRAST_ALLERGY_MAP[agent_lower]["snomed_class"])
        # 2. Check if it matches class_display
        for k, v in CONTRAST_ALLERGY_MAP.items():
            if v["class_display"].lower() == agent_lower:
                target_snomeds.add(v["snomed_class"])
            if v["generic"].lower() == agent_lower:
                target_rxnorms.add(v["rxnorm"])
                target_snomeds.add(v["snomed_class"])
                
    # Evaluate matches
    # A. Text-based matches (existing fallback)
    for agent in agents:
        for allergy in patient_allergies:
            if agent.lower() in allergy or allergy in agent.lower():
                matches.append({"agent": agent, "patient_allergy": allergy, "match_type": "text"})
                
    # B. Code-based matches (highest fidelity)
    for code_entry in patient_allergy_codes:
        sys = code_entry.get("system", "")
        val = code_entry.get("code", "")
        disp = code_entry.get("display", "")
        
        # Check RxNorm match
        if "rxnorm" in sys.lower() or sys == "http://www.nlm.nih.gov/research/umls/rxnorm":
            if val in target_rxnorms:
                matches.append({"agent": disp or agent, "patient_allergy": f"RxNorm Code {val}", "match_type": "code"})
        # Check SNOMED match
        if "snomed" in sys.lower() or sys == "http://snomed.info/sct":
            if val in target_snomeds:
                matches.append({"agent": disp or agent, "patient_allergy": f"SNOMED Class {val}", "match_type": "code"})
                
    # Deduplicate matches by (agent, patient_allergy)
    seen = set()
    deduped_matches = []
    for m in matches:
        key = (m["agent"].lower(), m["patient_allergy"].lower())
        if key not in seen:
            seen.add(key)
            deduped_matches.append(m)
            
    triggered = len(deduped_matches) > 0
    details = {"matched_allergies": deduped_matches} if triggered else {"status": "no_allergy_match"}
    return triggered, details


def _check_pregnancy(condition: dict, patient_data: dict) -> tuple:
    """Check pregnancy risk for females of childbearing age."""
    sex = patient_data.get("sex", "").lower()
    age = patient_data.get("age")
    
    required_sex = condition.get("sex", "female").lower()
    age_min = condition.get("age_min", 12)
    age_max = condition.get("age_max", 55)
    
    if sex != required_sex:
        return False, {"status": "not_applicable", "reason": f"Patient sex: {sex}"}
    
    if age is not None and (age < age_min or age > age_max):
        return False, {"status": "not_applicable", "reason": f"Patient age {age} outside {age_min}-{age_max}"}
    
    # If female of childbearing age, check HCG
    hcg = patient_data.get("hcg")
    details = {"sex": sex, "age": age}
    
    if not hcg or hcg.get("value") is None:
        details["hcg_status"] = "not_available"
        details["note"] = "β-HCG not on file — must verify pregnancy status before proceeding"
        return True, details
    
    hcg_value = hcg["value"]
    if isinstance(hcg_value, str):
        if "negative" in hcg_value.lower() or "not pregnant" in hcg_value.lower():
            details["hcg_status"] = "negative"
            return False, details
        elif "positive" in hcg_value.lower() or "pregnant" in hcg_value.lower():
            details["hcg_status"] = "positive"
            return True, details
    elif isinstance(hcg_value, (int, float)):
        if hcg_value < 5:  # <5 mIU/mL is negative
            details["hcg_status"] = "negative"
            details["hcg_value"] = hcg_value
            return False, details
        else:
            details["hcg_status"] = "positive"
            details["hcg_value"] = hcg_value
            return True, details
    
    details["hcg_status"] = "indeterminate"
    return True, details


def _check_bmi(condition: dict, patient_data: dict) -> tuple:
    """Check BMI-related conditions (e.g., oral contrast conditional)."""
    bmi = patient_data.get("bmi")
    if bmi is None:
        return False, {"status": "no_data"}
    
    if "bmi_lt" in condition and bmi < condition["bmi_lt"]:
        return True, {"patient_bmi": bmi, "threshold": condition["bmi_lt"]}
    if "bmi_gt" in condition and bmi > condition["bmi_gt"]:
        return True, {"patient_bmi": bmi, "threshold": condition["bmi_gt"]}
    
    return False, {"patient_bmi": bmi}


def evaluate_ir_lab_thresholds(
    lab_thresholds: List[Dict[str, Any]],
    patient_data: Dict[str, Any]
) -> List[LabCheckResult]:
    """
    Evaluate IR lab threshold rules against patient lab data.
    """
    results = []
    
    lab_key_map = {
        "INR": "inr",
        "Platelets": "platelets",
        "Hgb": "hgb",
        "Fibrinogen": "fibrinogen",
    }
    
    for thresh in lab_thresholds:
        lab_name = thresh["lab_name"]
        patient_key = lab_key_map.get(lab_name, lab_name.lower())
        patient_lab = patient_data.get(patient_key)
        
        patient_value = None
        patient_date = None
        is_stale = False
        
        if patient_lab and patient_lab.get("value") is not None:
            patient_value = patient_lab["value"]
            patient_date = patient_lab.get("date")
            
            # Check staleness
            max_hours = thresh.get("max_result_age_hours", 72)
            if patient_date:
                try:
                    rd = datetime.strptime(str(patient_date)[:10], "%Y-%m-%d")
                    age_hours = (datetime.now() - rd).total_seconds() / 3600
                    is_stale = age_hours > max_hours
                except (ValueError, TypeError):
                    pass
        
        # Evaluate threshold
        is_met = False
        if patient_value is not None and isinstance(patient_value, (int, float)):
            op = thresh["threshold_operator"]
            tv = thresh["threshold_value"]
            tvu = thresh.get("threshold_value_upper")
            
            if op == "<=":
                is_met = patient_value <= tv
            elif op == ">=":
                is_met = patient_value >= tv
            elif op == "<":
                is_met = patient_value < tv
            elif op == ">":
                is_met = patient_value > tv
            elif op == "between" and tvu is not None:
                is_met = tv <= patient_value <= tvu
            elif op == "==":
                is_met = patient_value == tv
        
        # If stale, treat as not met
        if is_stale:
            is_met = False
        
        results.append(LabCheckResult(
            lab_name=lab_name,
            required_operator=thresh["threshold_operator"],
            required_value=thresh["threshold_value"],
            patient_value=patient_value,
            patient_result_date=patient_date,
            is_met=is_met,
            is_stale=is_stale,
            action_if_not_met=thresh.get("action_if_not_met", "flag"),
            correction_guidance=thresh.get("correction_guidance"),
            sir_reference=thresh.get("sir_reference"),
        ))
    
    return results


def evaluate_ir_med_holds(
    med_holds: List[Dict[str, Any]],
    patient_data: Dict[str, Any]
) -> List[MedHoldAlert]:
    """
    Check patient's medications against IR hold requirements.
    Adjusts hold times for renal function if applicable.
    """
    patient_meds = [m.lower() for m in patient_data.get("medications", [])]
    patient_med_codes = patient_data.get("medication_codes", [])
    egfr_data = patient_data.get("egfr")
    egfr_value = egfr_data.get("value") if egfr_data else None
    
    alerts = []
    
    for hold in med_holds:
        med_name = hold["medication_name"]
        
        # Check if patient is on this medication
        # Match by generic name, brand name, or partial match
        is_taking = False
        
        # Code-based match first
        from medical_ontology import MEDICATION_MAP
        target_rxnorms = set()
        med_name_lower = med_name.lower().strip()
        
        # Parse names from the medication map
        for key, val in MEDICATION_MAP.items():
            if key in med_name_lower or med_name_lower in key:
                target_rxnorms.add(val["rxnorm"])
                
        for code_entry in patient_med_codes:
            sys = code_entry.get("system", "")
            val = code_entry.get("code", "")
            if "rxnorm" in sys.lower() or sys == "http://www.nlm.nih.gov/research/umls/rxnorm":
                if val in target_rxnorms:
                    is_taking = True
                    break
                    
        # Text fallback if not matched by code
        if not is_taking:
            search_terms = med_name.lower().replace("(", "").replace(")", "").split()
            for patient_med in patient_meds:
                if any(term in patient_med for term in search_terms if len(term) > 3):
                    is_taking = True
                    break
        
        hold_hours = hold["hold_hours_before"]
        renal_adjusted = False
        adjusted_hours = None
        
        # Adjust for renal function if applicable
        renal_adj = hold.get("renal_adjustment")
        if renal_adj and egfr_value is not None:
            if isinstance(renal_adj, str):
                renal_adj = json.loads(renal_adj)
            
            if egfr_value < 30 and "egfr_lt_30" in renal_adj:
                adjusted_hours = renal_adj["egfr_lt_30"].get("hold_hours_before", hold_hours)
                renal_adjusted = True
            elif 30 <= egfr_value < 50 and "egfr_30_50" in renal_adj:
                adjusted_hours = renal_adj["egfr_30_50"].get("hold_hours_before", hold_hours)
                renal_adjusted = True
        
        alerts.append(MedHoldAlert(
            medication_name=med_name,
            medication_class=hold.get("medication_class", ""),
            hold_hours_before=hold_hours,
            resume_hours_after=hold.get("resume_hours_after"),
            patient_is_taking=is_taking,
            renal_adjusted=renal_adjusted,
            adjusted_hold_hours=adjusted_hours,
            bridging_required=hold.get("bridging_required", False),
            bridging_protocol=hold.get("bridging_protocol"),
            sir_reference=hold.get("sir_reference"),
        ))
    
    return alerts


