def _extract_allergy(resource: dict, data: dict):
    """Parse an AllergyIntolerance resource for contrast agent allergies."""
    code = resource.get("code", {})
    text = code.get("text", "")
    if text:
        data["allergies"].append(text)
    for coding in code.get("coding", []):
        display = coding.get("display", "")
        if display and display not in data["allergies"]:
            data["allergies"].append(display)
        
        system = coding.get("system")
        code_val = coding.get("code")
        if system and code_val:
            if "allergy_codes" not in data:
                data["allergy_codes"] = []
            data["allergy_codes"].append({
                "system": system,
                "code": code_val,
                "display": display or text
            })


def _extract_medication(resource: dict, data: dict):
    """Parse medication resources for anticoagulant/antiplatelet detection.
    Handles both R4 (medicationCodeableConcept) and R5 (medication.concept) formats.
    """
    med_code = None
    
    # R4 format: medicationCodeableConcept
    if "medicationCodeableConcept" in resource:
        med_code = resource["medicationCodeableConcept"]
    # R5 format: medication.concept (CodeableReference)
    elif "medication" in resource:
        med_ref = resource["medication"]
        if isinstance(med_ref, dict):
            med_code = med_ref.get("concept", med_ref)
    # Fallback: medicationReference
    elif "medicationReference" in resource:
        med_code = resource["medicationReference"]
    
    if isinstance(med_code, dict):
        text = med_code.get("text", "")
        if text:
            data["medications"].append(text)
        for coding in med_code.get("coding", []):
            display = coding.get("display", "")
            if display and display not in data["medications"]:
                data["medications"].append(display)
            
            system = coding.get("system")
            code_val = coding.get("code")
            if system and code_val:
                if "medication_codes" not in data:
                    data["medication_codes"] = []
                data["medication_codes"].append({
                    "system": system,
                    "code": code_val,
                    "display": display or text
                })


def _extract_condition(resource: dict, data: dict):
    """Parse Condition resources for implants, pacemaker, claustrophobia."""
    code_text = ""
    codings = resource.get("code", {}).get("coding", [])
    for coding in codings:
        code_text += coding.get("display", "") + " " + coding.get("code", "") + " "
    code_text += resource.get("code", {}).get("text", "")
    code_text = code_text.lower()
    
    if any(term in code_text for term in ["pacemaker", "icd", "cardiac device"]):
        data["implants"].append("pacemaker")
    if any(term in code_text for term in ["aneurysm clip", "metallic clip", "metallic implant", "shrapnel", "cochlear"]):
        data["implants"].append("metallic implant")
    if "claustrophobia" in code_text:
        data["claustrophobia"] = True


def _extract_procedure(resource: dict, data: dict):
    """Parse a Procedure resource for history of recent exams."""
    code_text = ""
    codings = resource.get("code", {}).get("coding", [])
    for coding in codings:
        code_text += coding.get("display", "") + " " + coding.get("code", "") + " "
    code_text += resource.get("code", {}).get("text", "")
    code_text = code_text.lower()
    
    date_val = resource.get("performedDateTime", resource.get("performedPeriod", {}).get("start", ""))
    if isinstance(date_val, str) and date_val:
        date_val = date_val[:10]
        
    status = resource.get("status")
    
    modality = None
    if "ct" in code_text or "computed tomography" in code_text:
        modality = "CT"
    elif "mri" in code_text or "magnetic resonance" in code_text:
        modality = "MRI"
    elif "us" in code_text or "ultrasound" in code_text:
        modality = "US"
    elif "xray" in code_text or "radiograph" in code_text or "x-ray" in code_text:
        modality = "XRAY"
        
    if modality:
        data["recent_exams"].append({
            "modality": modality,
            "date": date_val,
            "name": resource.get("code", {}).get("text", "Previous Exam"),
            "status": status
        })


