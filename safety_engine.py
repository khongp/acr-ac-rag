def extract_patient_safety_data(fhir_bundle: dict) -> Dict[str, Any]:
    """
    Extract safety-relevant fields from a FHIR Bundle.
    Works with both synthetic bundles (from fhir_converter.py) and 
    real FHIR R4 bundles (from Epic/Cerner).
    
    Returns a standardized dict:
    {
        "sex": "female",
        "age": 34,
        "egfr": {"value": 65.0, "date": "2026-05-10"},
        "inr": {"value": 1.2, "date": "2026-05-14"},
        "platelets": {"value": 180000, "date": "2026-05-14"},
        "hgb": {"value": 12.5, "date": "2026-05-14"},
        "fibrinogen": {"value": 350.0, "date": "2026-05-14"},
        "hcg": {"value": "negative", "date": "2026-05-14"},
        "allergies": ["Omnipaque", "iodinated contrast"],
        "medications": ["Apixaban", "Aspirin"],
    }
    """
    data = {
        "sex": None,
        "age": None,
        "egfr": None,
        "inr": None,
        "platelets": None,
        "hgb": None,
        "fibrinogen": None,
        "hcg": None,
        "allergies": [],
        "medications": [],
    }
    
    entries = fhir_bundle.get("entry", [])
    
    for entry in entries:
        resource = entry.get("resource", {})
        rtype = resource.get("resourceType")
        
        if rtype == "Patient":
            data["sex"] = resource.get("gender")
            # Age from birthDate if available
            birth_date = resource.get("birthDate")
            if birth_date:
                try:
                    bd = datetime.strptime(birth_date[:10], "%Y-%m-%d")
                    data["age"] = (datetime.now() - bd).days // 365
                except (ValueError, TypeError):
                    pass
        
        elif rtype == "Observation":
            _extract_observation(resource, data)
        
        elif rtype == "AllergyIntolerance":
            _extract_allergy(resource, data)
        
        elif rtype in ("MedicationStatement", "MedicationRequest", "MedicationAdministration"):
            _extract_medication(resource, data)
    
    return data


def _extract_observation(resource: dict, data: dict):
    """Parse an Observation resource for lab values."""
    code_text = ""
    codings = resource.get("code", {}).get("coding", [])
    for coding in codings:
        code_text += coding.get("display", "") + " " + coding.get("code", "") + " "
    code_text += resource.get("code", {}).get("text", "")
    code_text = code_text.lower()
    
    value = None
    value_quantity = resource.get("valueQuantity", {})
    if value_quantity:
        value = value_quantity.get("value")
    elif resource.get("valueString"):
        value = resource.get("valueString")
    
    date = resource.get("effectiveDateTime", resource.get("issued", ""))
    if isinstance(date, str):
        date = date[:10]  # Keep just the date portion
    
    lab_entry = {"value": value, "date": date} if value is not None else None
    
    # Map to our standardized keys
    if any(term in code_text for term in ["egfr", "gfr", "glomerular"]):
        data["egfr"] = lab_entry
    elif any(term in code_text for term in ["inr", "6301-6"]):
        data["inr"] = lab_entry
    elif any(term in code_text for term in ["platelet", "777-3", "plt"]):
        data["platelets"] = lab_entry
    elif any(term in code_text for term in ["hemoglobin", "hgb", "718-7"]):
        data["hgb"] = lab_entry
    elif any(term in code_text for term in ["fibrinogen", "3255-7"]):
        data["fibrinogen"] = lab_entry
    elif any(term in code_text for term in ["hcg", "pregnancy", "beta-hcg"]):
        data["hcg"] = lab_entry


def _extract_allergy(resource: dict, data: dict):
    """Parse an AllergyIntolerance resource for contrast agent allergies."""
    code = resource.get("code", {})
    text = code.get("text", "")
    if text:
        data["allergies"].append(text)
    for coding in code.get("coding", []):
        display = coding.get("display", "")
        if display and display not in data["allergies"]:
            data["allergies"].append(display)


def _extract_medication(resource: dict, data: dict):
    """Parse medication resources for anticoagulant/antiplatelet detection.
    Handles both R4 (medicationCodeableConcept) and R5 (medication.concept) formats.
    """
    med_code = None
    
    # R4 format: medicationCodeableConcept
    if "medicationCodeableConcept" in resource:
        med_code = resource["medicationCodeableConcept"]
    # R5 format: medication.concept (CodeableReference)
    elif "medication" in resource:
        med_ref = resource["medication"]
        if isinstance(med_ref, dict):
            med_code = med_ref.get("concept", med_ref)
    # Fallback: medicationReference
    elif "medicationReference" in resource:
        med_code = resource["medicationReference"]
    
    if isinstance(med_code, dict):
        text = med_code.get("text", "")
        if text:
            data["medications"].append(text)
        for coding in med_code.get("coding", []):
            display = coding.get("display", "")
            if display and display not in data["medications"]:
                data["medications"].append(display)


