"""
Safety Engine — FHIR-Native Patient Safety Checks
===================================================
Evaluates contrast_rules (imaging) and ir_lab_thresholds/ir_med_holds (IR)
against patient data from FHIR resources.

Supports DUAL MODE:
  - Synthetic Mode (demo): Extracts safety data from text via LLM
  - Live Mode (production): Pulls from Epic/Cerner FHIR R4 endpoints

The engine returns a SafetyProfile: a list of flags, holds, and 
pre-medication requirements that are displayed alongside the Draft Protocol.
"""

import json
from datetime import datetime, timedelta
from typing import Optional, List, Dict, Any
from dataclasses import dataclass, field, asdict
from enum import Enum


class AlertSeverity(str, Enum):
    INFO = "info"
    WARNING = "warning"
    HARD_STOP = "hard_stop"


class DataSource(str, Enum):
    SYNTHETIC = "synthetic"
    FHIR_LIVE = "fhir_live"


@dataclass
class SafetyFlag:
    """A single safety alert generated by rule evaluation."""
    rule_type: str              # e.g., "egfr_check", "allergy_check"
    severity: str               # "info", "warning", "hard_stop"
    message: str                # Human-readable alert
    triggered: bool             # Whether the rule was actually triggered
    action: str                 # "flag", "require_premedication", "substitute_protocol", etc.
    details: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class MedHoldAlert:
    """An anticoagulation/antiplatelet hold requirement."""
    medication_name: str
    medication_class: str
    hold_hours_before: int
    resume_hours_after: Optional[int]
    patient_is_taking: bool         # Whether we detected this med in patient data
    renal_adjusted: bool = False    # Whether hold was adjusted for renal function
    adjusted_hold_hours: Optional[int] = None
    bridging_required: bool = False
    bridging_protocol: Optional[str] = None
    sir_reference: Optional[str] = None

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass 
class LabCheckResult:
    """Result of checking a specific lab value against a threshold."""
    lab_name: str
    required_operator: str
    required_value: float
    patient_value: Optional[float]
    patient_result_date: Optional[str]
    is_met: bool                    # Whether the lab meets the threshold
    is_stale: bool                  # Whether the result is too old
    action_if_not_met: str
    correction_guidance: Optional[str]
    sir_reference: Optional[str]

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class SafetyProfile:
    """
    Complete safety evaluation for a patient + protocol combination.
    This is what gets displayed in the "Draft Protocol" output.
    """
    data_source: str                          # "synthetic" or "fhir_live"
    overall_status: str = "clear"             # "clear", "warnings", "hard_stop"
    safety_flags: List[SafetyFlag] = field(default_factory=list)
    lab_checks: List[LabCheckResult] = field(default_factory=list)
    med_holds: List[MedHoldAlert] = field(default_factory=list)
    premedication_required: bool = False
    premedication_text: Optional[str] = None
    substitute_protocol_id: Optional[str] = None
    
    def to_dict(self) -> dict:
        return {
            "data_source": self.data_source,
            "overall_status": self.overall_status,
            "safety_flags": [f.to_dict() for f in self.safety_flags],
            "lab_checks": [l.to_dict() for l in self.lab_checks],
            "med_holds": [m.to_dict() for m in self.med_holds],
            "premedication_required": self.premedication_required,
            "premedication_text": self.premedication_text,
            "substitute_protocol_id": self.substitute_protocol_id,
        }

    def compute_overall_status(self):
        """Set overall_status based on the worst flag/lab/hold severity."""
        if any(f.triggered and f.severity == "hard_stop" for f in self.safety_flags):
            self.overall_status = "hard_stop"
        elif any(not lc.is_met and lc.action_if_not_met == "hard_stop" for lc in self.lab_checks):
            self.overall_status = "hard_stop"
        elif any(f.triggered for f in self.safety_flags) or any(not lc.is_met for lc in self.lab_checks):
            self.overall_status = "warnings"
        else:
            self.overall_status = "clear"


